// PodRestartHistorySpec defines the desired state of PodRestartHistory
type PodRestartHistorySpec struct {
	PodName       string      `json:"podName"`
	ContainerName string      `json:"containerName"`
	RestartCount  int32       `json:"restartCount"`
	RestartedAt   metav1.Time `json:"restartedAt"`
	Image         string      `json:"image,omitempty"`
}

// Diagnosis contains the root cause conclusion
type Diagnosis struct {
	Category          string `json:"category,omitempty"`          // Infrastructure, Application, Configuration, Dependency, Unknown
	RootCause         string `json:"rootCause,omitempty"`         // e.g. OOMKilled, LivenessProbeFailure, StartupProbeFailure, AppPanic, NodeEviction, Unknown
	Confidence        string `json:"confidence,omitempty"`        // High, Medium, Low
	Summary           string `json:"summary,omitempty"`
	RecommendedAction string `json:"recommendedAction,omitempty"` // Actionable mitigation guide for on-call engineers
}

// CulpritCode describes the suspected source code file and line responsible for the crash
type CulpritCode struct {
	Language  string `json:"language,omitempty"`
	Framework string `json:"framework,omitempty"`
	File      string `json:"file,omitempty"`
	Line      int    `json:"line,omitempty"`
	Function  string `json:"function,omitempty"`
}

// Evidence contains the raw collected data that led to the diagnosis
type Evidence struct {
	ExitCode                  *int32       `json:"exitCode,omitempty"`
	TerminationReason         string       `json:"terminationReason,omitempty"`
	ErrorClass                string       `json:"errorClass,omitempty"`
	ErrorLocation             string       `json:"errorLocation,omitempty"`
	CulpritCode               *CulpritCode `json:"culpritCode,omitempty"`
	MatchedEvents             []string     `json:"matchedEvents,omitempty"`
	MatchedLogPattern         string       `json:"matchedLogPattern,omitempty"`
	LastLogSnippet            string       `json:"lastLogSnippet,omitempty"`
	SidecarCascade            string       `json:"sidecarCascade,omitempty"`
	UptimeSeconds             *int64       `json:"uptimeSeconds,omitempty"`
	GracePeriodExceeded       bool         `json:"gracePeriodExceeded,omitempty"`
	ResourceConstraints       string       `json:"resourceConstraints,omitempty"`
	SecurityContextViolations string       `json:"securityContextViolations,omitempty"`
}

// ChainStep represents an event or causal step in the failure cascade
type ChainStep struct {
	Step        int    `json:"step"`
	Description string `json:"description"`
}

// Insight contains deep deterministic synthesis and actionable advice
type Insight struct {
	Engine          string      `json:"engine,omitempty"`
	Analyzed        bool        `json:"analyzed"`
	Language        string      `json:"language,omitempty"`
	Confidence      string      `json:"confidence,omitempty"`
	InferredContext string      `json:"inferredContext,omitempty"`
	SuggestedFix    string      `json:"suggestedFix,omitempty"`
	RootCauseChain  []ChainStep `json:"rootCauseChain,omitempty"`
}

// PodRestartHistoryStatus defines the observed state of PodRestartHistory
type PodRestartHistoryStatus struct {
	Diagnosis Diagnosis `json:"diagnosis,omitempty"`
	Evidence  Evidence  `json:"evidence,omitempty"`
	Insight   *Insight  `json:"insight,omitempty"`
}

